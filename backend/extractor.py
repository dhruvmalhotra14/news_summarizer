import json
import re
import urllib.parse
from bs4 import BeautifulSoup
import trafilatura
from curl_cffi import requests as curl_requests


def _clean_text(text: str) -> str:
    if not text:
        return ""
    text = re.sub(r"\n\s*\n+", "\n\n", text)
    return text.strip()


def _is_error_payload(text: str) -> bool:
    """Verifies that the content is real article prose and not an error page."""
    if not text or len(text.strip()) < 250:
        return True
    lower = text.lower()
    error_markers = [
        "403 forbidden",
        "cloudfront",
        "request could not be satisfied",
        "access denied",
        "attention required",
        "robot or human",
        "enable javascript",
        "generated by cloudfront",
        "block by cloudflare",
        "just a moment...",
    ]
    return any(marker in lower for marker in error_markers)


def _extract_from_json_ld(soup: BeautifulSoup) -> str:
    """Extracts article body directly from JSON-LD schema blocks."""
    for script in soup.find_all("script", type="application/ld+json"):
        if not script.string:
            continue
        try:
            data = json.loads(script.string.strip())
            items = data if isinstance(data, list) else [data]
            for item in items:
                if isinstance(item, dict):
                    if item.get("articleBody"):
                        return item["articleBody"].strip()
                    for graph_item in item.get("@graph", []):
                        if isinstance(graph_item, dict) and graph_item.get("articleBody"):
                            return graph_item["articleBody"].strip()
        except Exception:
            continue
    return ""


def _extract_soup_paragraphs(soup: BeautifulSoup) -> str:
    """Extracts clean article paragraphs."""
    for tag in soup(["script", "style", "nav", "header", "footer", "aside", "form"]):
        tag.decompose()

    container = soup.find(
        "div",
        class_=re.compile(
            r"(story-details|full-details|story_details|ie-content|art-content|wp-block-post-content|article-body|storycontent)",
            re.IGNORECASE,
        ),
    ) or soup.find(["article", "main"])

    target = container if container else soup
    paragraphs = [
        p.get_text(" ", strip=True)
        for p in target.find_all("p")
        if len(p.get_text(strip=True)) > 35
        and not p.get_text(strip=True).startswith(
            ("Also Read", "Click here", "Subscribe", "Explained |", "Follow us on")
        )
    ]
    return "\n\n".join(paragraphs) if len(paragraphs) >= 2 else ""


def _parse_html_payload(html: str) -> str:
    """Extracts clean text using JSON-LD, Trafilatura, and BeautifulSoup."""
    if not html or _is_error_payload(html):
        return ""

    soup = BeautifulSoup(html, "html.parser")

    # 1. JSON-LD schema (cleanest)
    json_ld = _extract_from_json_ld(soup)
    if json_ld and not _is_error_payload(json_ld):
        return _clean_text(json_ld)

    # 2. Trafilatura
    traf = trafilatura.extract(
        html,
        include_comments=False,
        include_tables=False,
        no_fallback=False,
    )
    if traf and not _is_error_payload(traf):
        return _clean_text(traf)

    # 3. DOM fallback
    dom = _extract_soup_paragraphs(soup)
    if dom and not _is_error_payload(dom):
        return _clean_text(dom)

    return ""


def _fetch_via_google_proxy(url: str) -> str:
    """
    Tunnels through Google's translation mirror.
    CloudFront/Cloudflare will NEVER block Google's crawler IPs,
    allowing Streamlit Cloud to pull the raw HTML safely.
    """
    try:
        clean_url = url.split("?")[0].rstrip("/")
        # Google Translate unblock proxy format
        encoded_domain = clean_url.replace("https://", "").replace("http://", "")
        dash_domain = encoded_domain.replace(".", "-").replace("/", ".")
        
        # Method 1: Google Translate Proxy Engine
        gt_url = f"https://translate.google.com/m?sl=auto&tl=en&u={urllib.parse.quote(clean_url)}"
        resp = curl_requests.get(
            gt_url,
            impersonate="chrome120",
            timeout=12,
            headers={
                "User-Agent": "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36",
                "Referer": "https://translate.google.com/",
            }
        )
        if resp.status_code == 200:
            extracted = _parse_html_payload(resp.text)
            if extracted:
                return extracted
    except Exception:
        pass

    # Method 2: Jina Reader with explicit bypass headers
    try:
        jina_url = f"https://r.jina.ai/{clean_url}"
        resp = curl_requests.get(
            jina_url,
            timeout=12,
            headers={
                "x-no-cache": "true",
                "x-return-format": "markdown",
                "User-Agent": "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36"
            }
        )
        if resp.status_code == 200 and not _is_error_payload(resp.text):
            # Strip markdown title headers if needed
            body = re.sub(r"^Title:.*?\n", "", resp.text, flags=re.MULTILINE)
            body = re.sub(r"^URL Source:.*?\n", "", body, flags=re.MULTILINE)
            return _clean_text(body)
    except Exception:
        pass

    return ""


def extract_article(url: str) -> str:
    clean_url = url.strip()

    # If it is Indian Express, immediately route via Google's proxy tunnel
    if "indianexpress.com" in clean_url:
        text = _fetch_via_google_proxy(clean_url)
        if text:
            return text

    # Standard direct fetch for other sites (The Hindu, NDTV, BBC, TOI)
    try:
        resp = curl_requests.get(
            clean_url,
            impersonate="chrome120",
            timeout=10,
            headers={
                "Referer": "https://www.google.com/",
                "Accept-Language": "en-US,en;q=0.9",
            },
        )
        if resp.status_code == 200:
            extracted = _parse_html_payload(resp.text)
            if extracted:
                return extracted
    except Exception:
        pass

    # Trafilatura standard fetch
    try:
        html = trafilatura.fetch_url(clean_url)
        if html:
            extracted = _parse_html_payload(html)
            if extracted:
                return extracted
    except Exception:
        pass

    # Fallback to Google proxy tunnel for any other domain blocked by CloudFront
    fallback = _fetch_via_google_proxy(clean_url)
    if fallback:
        return fallback

    return ""